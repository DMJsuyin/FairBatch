import fs from 'node:fs';
import path from 'node:path';
import solc from 'solc';
export function compile() {
  const sources = Object.fromEntries(fs.readdirSync('contracts').filter(f => f.endsWith('.sol') && !f.startsWith('._')).map(f => [f, {content: fs.readFileSync(`contracts/${f}`, 'utf8')}]));
  const input = {language: 'Solidity', sources, settings: {optimizer: {enabled:true, runs:200}, viaIR:true, evmVersion:'shanghai', outputSelection:{'*':{'*':['abi','evm.bytecode.object','evm.deployedBytecode.object']}}}};
  const output = JSON.parse(solc.compile(JSON.stringify(input), {import:(name:string)=>({contents:fs.readFileSync(path.join('node_modules', name),'utf8')})}));
  for (const e of output.errors ?? []) { if(e.severity === 'error') throw new Error(e.formattedMessage); console.warn(e.formattedMessage); }
  fs.mkdirSync('artifacts',{recursive:true});
  const artifacts: Record<string, {abi:any; bytecode:`0x${string}`}> = {};
  for (const [file, contracts] of Object.entries<any>(output.contracts)) {
    if (!Object.hasOwn(sources, file)) continue;
    for (const [name,c] of Object.entries<any>(contracts)) {
      artifacts[name] = {abi:c.abi, bytecode:`0x${c.evm.bytecode.object}`};
      fs.writeFileSync(`artifacts/${name}.json`, JSON.stringify(artifacts[name],null,2));
      console.log(`${name}: ${c.evm.deployedBytecode.object.length/2} deployed bytes`);
    }
  }
  fs.writeFileSync('src/abi.ts', `// Generated by npm run compile.\nexport const bookAbi = ${JSON.stringify(artifacts.OrderBook.abi)} as const;\nexport const tokenAbi = ${JSON.stringify(artifacts.DemoToken.abi)} as const;\n${artifacts.FairBatch ? `export const fairBatchAbi = ${JSON.stringify(artifacts.FairBatch.abi)} as const;\n` : ''}`);
  return artifacts;
}
if (process.argv[1]?.endsWith('compile.ts')) compile();
